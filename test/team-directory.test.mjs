import test from 'node:test';
import assert from 'node:assert/strict';
import {start,client} from './helpers.mjs';

test('team board directory: membership, private preferences, access and persistence',async t=>{
 let server=await start();t.after(()=>server.stop());
 const admin=client(server.base),reader=client(server.base),outsider=client(server.base),password='Directory-test-password-2026';
 await admin.request('/setup','POST',{login:'admin',name:'Admin',password,demo:false});
 const project=(await admin.request('/projects'))[0].id,base=`/projects/${project}`;
 const defaultTeam=(await admin.request(base)).teams[0].id;
 const uid=(await admin.request('/users','POST',{login:'reader',name:'Reader',password})).id;
 await admin.request(base+'/members','POST',{user_id:uid,role:'reader'});
 await reader.request('/login','POST',{login:'reader',password});
 const team=(await admin.request(base+'/teams','POST',{name:'Extra team',areas:'Extra'})).id;
 assert.equal((await reader.request(base+'/boards-directory')).find(t=>t.id===team).is_member,0);
 await admin.request(base+`/teams/${team}/members/${uid}`,'PUT',{});
 assert.equal((await reader.request(base+'/boards-directory')).find(t=>t.id===team).is_member,1);
 assert.deepEqual((await reader.request(base+`/teams/${team}/members`)).members.map(m=>m.name).sort(),['Admin','Reader']);
 await reader.request(base+`/teams/${team}/members/${uid}`,'DELETE',{}, {status:403});
 await reader.request(base+`/teams/${team}/favorite`,'PUT',{favorite:true});
 await reader.request(base+`/teams/${team}/visit`,'POST',{});
 let rows=await reader.request(base+'/boards-directory');
 assert.equal(rows.find(t=>t.id===team).favorite,1);assert.ok(rows.find(t=>t.id===team).last_visited);
 assert.equal((await admin.request(base+'/boards-directory')).find(t=>t.id===team).favorite,0);
 await reader.request(base+`/teams/${team}/favorite`,'PUT',{favorite:'yes'}, {status:400});
 await reader.request(base+`/teams/${team}/favorite`,'PUT',{favorite:false},{noCsrf:true,status:403});
 await outsider.request(base+'/boards-directory','GET',undefined,{status:401});
 const privateProject=(await admin.request('/projects','POST',{name:'Private'})).id;
 const otherTeam=(await admin.request(`/projects/${privateProject}`)).teams[0].id;
 await reader.request(`/projects/${privateProject}/boards-directory`,'GET',undefined,{status:404});
 await admin.request(base+`/teams/${otherTeam}/favorite`,'PUT',{favorite:true},{status:404});
 const absent=(await admin.request('/users','POST',{login:'absent',name:'Absent',password})).id;
 await admin.request(base+`/teams/${team}/members/${absent}`,'PUT',{}, {status:400});
 const directory=server.directory;await server.stop();server=await start({directory});
 const returning=client(server.base);await returning.request('/login','POST',{login:'reader',password});
 rows=await returning.request(base+'/boards-directory');assert.equal(rows.find(t=>t.id===team).favorite,1);assert.ok(rows.find(t=>t.id===team).last_visited);assert.equal(rows.find(t=>t.id===team).is_member,1);
 const owner=client(server.base);await owner.request('/login','POST',{login:'admin',password});
 await owner.request(base+`/members/${uid}`,'DELETE',{});
 await returning.request(base+'/boards-directory','GET',undefined,{status:404});
 await owner.request(base+'/members','POST',{user_id:uid,role:'reader'});
 rows=await returning.request(base+'/boards-directory');assert.equal(rows.find(t=>t.id===team).is_member,0);assert.equal(rows.find(t=>t.id===team).favorite,0);assert.equal(rows.find(t=>t.id===team).last_visited,'');
 assert.equal((await owner.request(base+'/boards-directory')).find(t=>t.id===defaultTeam).is_member,1);
});
